#!/usr/bin/env bash
# Write PostgreSQL migration SQL from the Prisma datamodel.
# This does not read prisma/migrations and does not change prisma/schema.prisma.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/prisma/migrations-postgres/0001_init.sql"
mkdir -p "$(dirname "$out")"
mkdir -p "$root/node_modules/.cache"
schema="$(mktemp "$root/node_modules/.cache/hn-postgres-schema.XXXXXX.prisma")"
trap 'rm -f "$schema"' EXIT

python3 - "$root" "$schema" <<'PY'
import pathlib, sys
root, dest = sys.argv[1:]
text = pathlib.Path(root, "prisma/schema.prisma").read_text()
old = 'provider = "sqlite"'
if old not in text:
    raise SystemExit("sqlite provider was not found")
pathlib.Path(dest).write_text(text.replace(old, 'provider = "postgresql"', 1))
PY

# The datasource URL is only parsed. No database connection is required.
export DATABASE_URL="${DATABASE_URL:-postgresql://hn:hn@127.0.0.1:5432/hackernews}"
case "$DATABASE_URL" in
  postgresql://*|postgres://*) ;;
  *)
    export DATABASE_URL="postgresql://hn:hn@127.0.0.1:5432/hackernews"
    ;;
esac

npx prisma migrate diff \
  --from-empty \
  --to-schema-datamodel "$schema" \
  --script > "$out.body"

python3 - "$out" "$out.body" <<'PY'
import pathlib, sys
dest, body = sys.argv[1:]
header = """-- Generated by: npx prisma migrate diff --from-empty --to-schema-datamodel --script
-- Source: prisma/schema.prisma with the datasource provider set to postgresql.
-- Do not replay prisma/migrations. Those files are SQLite SQL.
-- Regenerate with: bash scripts/generate-postgres-migration.sh

"""
pathlib.Path(dest).write_text(header + pathlib.Path(body).read_text())
pathlib.Path(body).unlink()
PY

if ! grep -q 'TIMESTAMP(3)' "$out"; then
  echo "Generated SQL is missing PostgreSQL timestamps" >&2
  exit 1
fi
if grep -q 'DATETIME' "$out"; then
  echo "Generated SQL still contains SQLite DATETIME" >&2
  exit 1
fi
echo "Wrote $out"
